/**************************************************************
*函数功能描述 ：初始化timer
*函数参数 ：
*函数返回值 ：
*备注：
**************************************************************/
void hal_timer_init(void)
{
    const tim_config_t timer_cfg =
    {
        .mode = TIM_TIMER_MODE,
        .config.timer =
        {
            .period_us = HAL_TIMER_TIM0_BASE_US,//中断时间，us
            .callback = hal_timer_tim0_handler,
        },
    };

    // Timer init
    tim_init();
    tim_config(HS_TIM0, &timer_cfg);
    tim_start(HS_TIM0);
}

/**************************************************************
*函数功能描述 ：去初始化timer，停止计时
*函数参数 ：
*函数返回值 ：
*备注：
**************************************************************/
void hal_timer_deinit(void)
{
    tim_stop(HS_TIM0);
}

