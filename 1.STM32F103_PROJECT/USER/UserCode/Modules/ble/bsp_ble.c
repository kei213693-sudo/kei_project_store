/**************************************************************
*函数功能描述 ：ble初始化
*函数参数 ：u8Mode，0掉电初始化方式，1休眠唤醒后初始化
*函数返回值 ：
*备注：
**************************************************************/
void bsp_ble_init(uint8_t u8Mode)
{
    if(0 == u8Mode)
    {
        bsp_ble_power_down_process();
    }
    else
    {
        bsp_ble_wakeup_process();
    }
}

