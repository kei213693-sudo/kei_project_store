/**************************************************************
*函数功能描述 ：通知方式发送数据,slave--->master
*函数参数 ：conidx，连接设备索引
            pData，数据指针
            length，数据长度
*函数返回值 ：
*备注：
**************************************************************/
void bsp_ble_send_data_notify(void *pData)
{
    if(NULL != pData)
    {
        if(ATK_BLE03_CONNECTED == atk_ble03_get_conn_sta())
        {
            typedef struct
            {
                uint32_t enOpt; //app层自定义操作码
                uint32_t u32Len;//该数据长度
                uint8_t *pData;//指向实际要操作的数据
                uint8_t res[3];
            }Param_t;//格式参考APP_BLE_QUEUE_REC_T
            Param_t *pStData = (Param_t *)pData;
            atk_ble03_uart_tx(pStData->pData,(uint16_t)pStData->u32Len,BSP_BLE_TX_TIMEOUT);
        }
        else
        {//没有建立连接，直接退出，不然强制调用atk_ble03_uart_tx（）会出现硬件错误
            printf("atk_ble03 is not connect!!!\r\n");
        }
    }
}

