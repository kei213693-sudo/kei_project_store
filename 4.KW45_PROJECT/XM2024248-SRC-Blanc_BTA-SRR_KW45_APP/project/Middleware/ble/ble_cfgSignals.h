#ifndef SIGNALS_BLE_BLE_CFGSIGNALS_H_
#define SIGNALS_BLE_BLE_CFGSIGNALS_H_
#include "stdint.h"

typedef struct{
	uint8_t device_address[6];			/*MAC address of keyfob.*/
	uint8_t key_id[16];					/*Key ID which is generated by TSP.*/
	uint8_t device_id[16];				/*Keyfob unique device id*/
	uint8_t device_type;				/*0x0A for keyfob*/
										/*0xA1 for BLE-based Android*/
										/*0xA2 for BLE-based iOS device*/
										/*0x00 for Mobile APP based on HCE*/
										/*0x01 for NFC Card.*/
										/*0x02 for Mobile APP based on eSE*/
										/*0x10 for other devices.*/
	uint8_t secure_key[32];
	uint8_t vehicle_id[16];
}keyFobData_t;

typedef struct{
	uint8_t vehicle_id[16];			/*Current vehicle id*/
	uint8_t VDF_cert;				/*VDF cert based on ECC*/
	uint8_t VDF_pri_key;			/*Asymmetric private key for VDF.*/
	uint8_t crl;					/*Certificate Revocation List*/
	uint8_t trust_chain;			/*PKI trust chain of Ica_VirtualKey and Ica_Web*/
	uint8_t dk_signer_pub_key;		/*Digital-key signer public key.*/
	uint8_t pass_key[32];			/*Passkey used to new device pairing*/
}phoneData_t;

extern keyFobData_t keyFobData;
extern phoneData_t	phoneData;

#endif /* SIGNALS_BLE_BLE_CFGSIGNALS_H_ */
