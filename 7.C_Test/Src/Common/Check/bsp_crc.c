unsigned int bsp_crc32_calculate(unsigned char *pData, unsigned int len)
{
    unsigned char i = 0;
    unsigned int crc32 = 0xffffffff;

    if((NULL != pData) && (0 != len))
    {
        while(len--)
        {
            crc32 ^= (*pData++);
            for(i = 0; i < 8; i++)
            {
                if(crc32 & 0x0001)
                {
                    crc32 = (crc32 >> 1) ^ 0xEDB88320;//0x04C11DB7的反转值
                }
                else
                {
                    crc32 >>= 1;
                }
            }
        }
    }
    return ~crc32;
}

