{
    unsigned char i = 0;
    unsigned short int crc16 = 0;

    if((NULL != pData) && (0 != len))
    {
        while(len--)
        {
            crc16 ^= (unsigned short int)(*pData++) << 8;
            for(i = 0; i < 8; i++)
            {
                if(crc16 & 0x8000)
                {
                    crc16 = (crc16 << 1) ^ 0x1021;
                }
                else
                {
                    crc16 <<= 1;
                }
            }
        }
    }
    return crc16;
}

